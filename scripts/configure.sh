#!/bin/bash
# Turns .env into the app's build settings: Config/Secrets.xcconfig (git ignores it), which Config/Priva.xcconfig
# includes. Run it after changing .env; the build stops with a pointer here while it's missing or out of date.
set -eu
source "$(dirname "$0")/env.sh"
load_env
need PRIVA_TEAM_ID PRIVA_SUPABASE_HOST PRIVA_SUPABASE_PUBLISHABLE_KEY PRIVA_RELAY_HOST PRIVA_TOKEN_KEY_ID PRIVA_PASS_KEY_ID

check() {   # name value pattern what
  [[ "$2" =~ $3 ]] || { echo "$1 doesn't look like $4: $2" >&2; exit 1; }
}
check PRIVA_TEAM_ID "$PRIVA_TEAM_ID" '^[A-Z0-9]{10}$' "a 10-character Apple team ID"
check PRIVA_SUPABASE_HOST "$PRIVA_SUPABASE_HOST" '^[a-z0-9-]+(\.[a-z0-9-]+)+$' "a host name (no https://)"
check PRIVA_RELAY_HOST "$PRIVA_RELAY_HOST" '^[a-z0-9-]+(\.[a-z0-9-]+)+$' "a host name (no https://)"
check PRIVA_SUPABASE_PUBLISHABLE_KEY "$PRIVA_SUPABASE_PUBLISHABLE_KEY" '^sb_publishable_[A-Za-z0-9_-]+$' "a publishable key (sb_publishable_…)"
# The active key's id, then optionally the standby's after a comma (scripts/standby_keys.sh makes it).
check PRIVA_TOKEN_KEY_ID "$PRIVA_TOKEN_KEY_ID" '^[0-9a-f]{64}(,[0-9a-f]{64})?$' "a SHA-256 in hex (or two, comma-separated)"
check PRIVA_PASS_KEY_ID "$PRIVA_PASS_KEY_ID" '^[0-9a-f]{64}(,[0-9a-f]{64})?$' "a SHA-256 in hex (or two, comma-separated)"
dev_key=${PRIVA_DEV_PURCHASE_KEY:-}
if [ -n "$dev_key" ]; then
  check PRIVA_DEV_PURCHASE_KEY "$dev_key" '^[0-9a-f]{64}$' "64 hex characters (openssl rand -hex 32)"
else
  echo "Note: no PRIVA_DEV_PURCHASE_KEY in .env: Debug builds can't get development purchases." >&2
fi

mkdir -p "$ROOT/Config"
out="$ROOT/Config/Secrets.xcconfig"
tmp="$out.tmp"
cat > "$tmp" <<EOF
// Generated by scripts/configure.sh from .env. Not committed; edit .env and run the script again.
PRIVA_TEAM_ID = $PRIVA_TEAM_ID
PRIVA_SUPABASE_HOST = $PRIVA_SUPABASE_HOST
PRIVA_SUPABASE_PUBLISHABLE_KEY = $PRIVA_SUPABASE_PUBLISHABLE_KEY
PRIVA_RELAY_HOST = $PRIVA_RELAY_HOST
PRIVA_TOKEN_KEY_ID = $PRIVA_TOKEN_KEY_ID
PRIVA_PASS_KEY_ID = $PRIVA_PASS_KEY_ID
// Debug builds only: a Release build must never carry it.
PRIVA_DEV_PURCHASE_KEY[config=Debug] = $dev_key
EOF
if cmp -s "$tmp" "$out"; then rm "$tmp"; else mv "$tmp" "$out"; fi   # unchanged: no rebuild
touch "$out"                                                        # newer than .env: the build's check passes
echo "Config/Secrets.xcconfig is up to date."
